-- Match Intelligence AI — Faz 3: model kayıt defteri ve değiştirilemez tahminler.
--
--   * Model sürümleri: eğitim ayarları, Optuna denemeleri, doğrulama/test metrikleri, veri parmak izi.
--     Model dosyası JSON (pickle yok). Kapsam (lig) başına en fazla bir şampiyon.
--   * Tahminler: maç başlamadan önce üretilmiş olmak zorunda; yazıldıktan sonra DEĞİŞTİRİLEMEZ ve
--     SİLİNEMEZ (tetikleyici). Tahmin anındaki özellikler ve veri anlık görüntüsü saklanır.
--   * Sonuçlar ayrı tabloda, tahminle bire bir; o da değiştirilemez.

CREATE TABLE ml_model_versions (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_key         varchar(64) NOT NULL,           -- ör. 'competition:12'
    scope             jsonb NOT NULL,
    family            varchar(32) NOT NULL DEFAULT 'ensemble_1x2',
    status            varchar(16) NOT NULL DEFAULT 'challenger'
                      CHECK (status IN ('challenger', 'champion', 'retired')),
    created_at        timestamptz NOT NULL DEFAULT now(),
    trained_until     timestamptz NOT NULL,
    seed              integer NOT NULL,
    config            jsonb NOT NULL,
    components        jsonb NOT NULL,                 -- {ad: ağırlık}
    excluded          jsonb NOT NULL DEFAULT '{}'::jsonb,
    temperature       double precision NOT NULL CHECK (temperature > 0),
    metrics           jsonb NOT NULL,                 -- doğrulama + test (model başına)
    feature_importance jsonb NOT NULL DEFAULT '{}'::jsonb,
    data_fingerprint  char(64) NOT NULL,
    n_rows            integer NOT NULL CHECK (n_rows > 0),
    artifact          jsonb NOT NULL,
    promoted_at       timestamptz,
    promoted_by       uuid REFERENCES users(id)
);
CREATE UNIQUE INDEX ux_ml_model_versions_champion ON ml_model_versions (scope_key) WHERE status = 'champion';
CREATE INDEX ix_ml_model_versions_scope ON ml_model_versions (scope_key, created_at DESC);

CREATE TABLE ml_tuning_trials (
    model_version_id  bigint NOT NULL REFERENCES ml_model_versions(id) ON DELETE CASCADE,
    number            integer NOT NULL,
    state             varchar(16) NOT NULL,
    value             double precision,
    params            jsonb NOT NULL,
    PRIMARY KEY (model_version_id, number)
);

CREATE TABLE ml_predictions (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fixture_id          bigint NOT NULL REFERENCES football_fixtures(id),
    model_version_id    bigint NOT NULL REFERENCES ml_model_versions(id),
    created_at          timestamptz NOT NULL,
    kickoff_at          timestamptz NOT NULL,
    status              varchar(16) NOT NULL CHECK (status IN ('published', 'abstained')),
    probabilities       jsonb,                         -- piyasalar; çekimserlikte NULL
    components          jsonb NOT NULL DEFAULT '{}'::jsonb,
    uncertainty         jsonb NOT NULL DEFAULT '{}'::jsonb,
    reliability         varchar(8) NOT NULL CHECK (reliability IN ('high', 'medium', 'low')),
    data_quality        jsonb NOT NULL DEFAULT '{}'::jsonb,
    model_agreement     double precision,
    abstain_reasons     jsonb NOT NULL DEFAULT '[]'::jsonb,
    features            jsonb NOT NULL,
    feature_hash        char(64) NOT NULL,
    data_snapshot       jsonb NOT NULL,
    CONSTRAINT prediction_before_kickoff CHECK (created_at < kickoff_at),
    CONSTRAINT published_has_probabilities CHECK ((status = 'published') = (probabilities IS NOT NULL))
);
CREATE INDEX ix_ml_predictions_fixture ON ml_predictions (fixture_id, created_at DESC);
CREATE INDEX ix_ml_predictions_kickoff ON ml_predictions (kickoff_at);
CREATE TRIGGER trg_ml_predictions_immutable BEFORE UPDATE OR DELETE ON ml_predictions
    FOR EACH ROW EXECUTE FUNCTION reject_modification();
CREATE TRIGGER trg_ml_predictions_no_truncate BEFORE TRUNCATE ON ml_predictions
    FOR EACH STATEMENT EXECUTE FUNCTION reject_modification();

CREATE TABLE ml_prediction_outcomes (
    prediction_id   bigint PRIMARY KEY REFERENCES ml_predictions(id),
    settled_at      timestamptz NOT NULL,
    home_goals      smallint NOT NULL CHECK (home_goals >= 0),   -- normal süre (90')
    away_goals      smallint NOT NULL CHECK (away_goals >= 0),
    outcome         varchar(8) NOT NULL CHECK (outcome IN ('home', 'draw', 'away')),
    brier           double precision,
    log_loss        double precision
);
CREATE TRIGGER trg_ml_prediction_outcomes_immutable BEFORE UPDATE OR DELETE ON ml_prediction_outcomes
    FOR EACH ROW EXECUTE FUNCTION reject_modification();
