-- Match Intelligence AI — Faz 6: paketler, haklar, abonelikler, siparişler, ödeme olayları, lisanslar.
--
--   * Fiyat girilmemiş paket satışa açılamaz (fiyat satırı yoksa ödeme başlatılamaz). Uydurma fiyat yok.
--   * Ödeme olayı imzası doğrulanmadan işlenmez; aynı olay (sağlayıcı + olay kimliği) bir kez işlenir.
--   * Sipariş başına en fazla bir başarılı ödeme; tutar/para birimi uyuşmazlığında teslim yok (inceleme).
--   * Lisans anahtarı düz metin saklanmaz: yalnızca HMAC-SHA256(pepper) özeti ve son 4 karakter.

CREATE TABLE plans (
    code       varchar(16) PRIMARY KEY CHECK (code ~ '^[A-Z]+$'),
    name       text NOT NULL,
    tagline    text NOT NULL,
    sort       smallint NOT NULL,
    is_public  boolean NOT NULL DEFAULT true
);

CREATE TABLE plan_entitlements (
    plan_code  varchar(16) NOT NULL REFERENCES plans(code),
    key        varchar(48) NOT NULL CHECK (key ~ '^[a-z_]+\.[a-z_]+$'),
    value      jsonb NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (plan_code, key)
);

CREATE TABLE plan_prices (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_code     varchar(16) NOT NULL REFERENCES plans(code),
    period        varchar(8) NOT NULL CHECK (period IN ('monthly', 'yearly')),
    amount_minor  bigint NOT NULL CHECK (amount_minor > 0),
    currency      char(3) NOT NULL DEFAULT 'TRY',
    active        boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL,
    created_by    uuid REFERENCES users(id),
    CHECK (plan_code <> 'FREE')
);
CREATE UNIQUE INDEX ux_plan_prices_active ON plan_prices (plan_code, period) WHERE active;

CREATE TABLE orders (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100001) PRIMARY KEY,
    public_id            uuid NOT NULL UNIQUE,
    user_id              uuid NOT NULL REFERENCES users(id),
    plan_code            varchar(16) NOT NULL REFERENCES plans(code),
    period               varchar(8) NOT NULL CHECK (period IN ('monthly', 'yearly')),
    price_id             bigint NOT NULL REFERENCES plan_prices(id),
    amount_minor         bigint NOT NULL CHECK (amount_minor > 0),
    currency             char(3) NOT NULL,
    status               varchar(12) NOT NULL DEFAULT 'pending'
                         CHECK (status IN ('pending', 'paid', 'failed', 'refunded', 'review')),
    provider             varchar(16) NOT NULL,
    test_mode            boolean NOT NULL,
    provider_ref         text,
    provider_payment_id  text,
    consent              jsonb NOT NULL,
    created_at           timestamptz NOT NULL,
    paid_at              timestamptz,
    refunded_at          timestamptz,
    refund_ref           text,
    note                 text,
    CHECK ((status IN ('paid', 'refunded')) = (paid_at IS NOT NULL) OR status = 'review')
);
CREATE INDEX ix_orders_user ON orders (user_id, created_at DESC);
CREATE INDEX ix_orders_status ON orders (status, created_at DESC);

CREATE TABLE payment_events (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider         varchar(16) NOT NULL,
    event_id         text,
    received_at      timestamptz NOT NULL,
    signature_valid  boolean NOT NULL,
    event_type       varchar(32),
    order_id         bigint REFERENCES orders(id),
    payload_sha256   char(64) NOT NULL,
    result           varchar(24) NOT NULL,
    detail           text
);
CREATE UNIQUE INDEX ux_payment_events_once ON payment_events (provider, event_id) WHERE signature_valid AND event_id IS NOT NULL;
CREATE TRIGGER trg_payment_events_immutable BEFORE UPDATE OR DELETE ON payment_events
    FOR EACH ROW EXECUTE FUNCTION reject_modification();

CREATE TABLE licenses (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_digest         bytea NOT NULL UNIQUE CHECK (length(key_digest) = 32),
    key_hint           varchar(4) NOT NULL,
    plan_code          varchar(16) NOT NULL REFERENCES plans(code) CHECK (plan_code <> 'FREE'),
    duration_days      integer NOT NULL CHECK (duration_days BETWEEN 1 AND 3660),
    max_activations    integer NOT NULL DEFAULT 1 CHECK (max_activations BETWEEN 1 AND 10000),
    activations_count  integer NOT NULL DEFAULT 0,
    status             varchar(8) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
    redeem_before      timestamptz NOT NULL,
    created_at         timestamptz NOT NULL,
    created_by         uuid REFERENCES users(id),
    revoked_at         timestamptz,
    note               text,
    CHECK (activations_count BETWEEN 0 AND max_activations)
);

CREATE TABLE subscriptions (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               uuid NOT NULL REFERENCES users(id),
    plan_code             varchar(16) NOT NULL REFERENCES plans(code) CHECK (plan_code <> 'FREE'),
    status                varchar(10) NOT NULL CHECK (status IN ('active', 'canceled', 'refunded', 'revoked')),
    source                varchar(8) NOT NULL CHECK (source IN ('payment', 'license', 'admin')),
    started_at            timestamptz NOT NULL,
    current_period_end    timestamptz NOT NULL,
    cancel_at_period_end  boolean NOT NULL DEFAULT false,
    canceled_at           timestamptz,
    order_id              bigint UNIQUE REFERENCES orders(id),
    license_id            bigint REFERENCES licenses(id),
    granted_by            uuid REFERENCES users(id),
    created_at            timestamptz NOT NULL,
    CHECK (current_period_end > started_at),
    CHECK ((source = 'payment') = (order_id IS NOT NULL)),
    CHECK ((source = 'license') = (license_id IS NOT NULL))
);
CREATE INDEX ix_subscriptions_user ON subscriptions (user_id, current_period_end DESC);

CREATE TABLE license_activations (
    license_id       bigint NOT NULL REFERENCES licenses(id),
    user_id          uuid NOT NULL REFERENCES users(id),
    activated_at     timestamptz NOT NULL,
    ip               inet,
    subscription_id  bigint NOT NULL REFERENCES subscriptions(id),
    PRIMARY KEY (license_id, user_id)
);

CREATE TABLE usage_daily (
    user_id  uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day      date NOT NULL,
    key      varchar(48) NOT NULL,
    count    integer NOT NULL DEFAULT 0 CHECK (count >= 0),
    PRIMARY KEY (user_id, day, key)
);

