-- Match Intelligence AI — Faz 2: futbol verisi.
--
-- İlkeler:
--   * Tüm zamanlar UTC (timestamptz). Arayüz Europe/Istanbul'a çevirir.
--   * Sağlayıcıdan gelen her kayıtta kaynak (provider + external_id) ve çekilme zamanı (fetched_at)
--     bulunur; sağlayıcı bildiriyorsa kaynaktaki güncelleme zamanı (source_updated_at) da.
--   * Daha eski bir yanıt daha yeni veriyi ezemez (fetched_at koşullu güncelleme, uygulamada).
--   * Veri yoksa alan NULL kalır; uydurma/varsayılan değer yazılmaz.

CREATE TABLE football_countries (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL UNIQUE,
    code        varchar(8),
    flag_url    text
);

CREATE TABLE football_competitions (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider           varchar(32) NOT NULL,
    external_id        text NOT NULL,
    name               text NOT NULL,
    type               varchar(16) NOT NULL DEFAULT 'league' CHECK (type IN ('league', 'cup', 'other')),
    country_id         bigint REFERENCES football_countries(id),
    logo_url           text,
    -- Takip edilen lig: puan durumu, kadro, istatistik gibi ek istekler yalnızca bunlar için yapılır.
    is_active          boolean NOT NULL DEFAULT false,
    fetched_at         timestamptz NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (provider, external_id)
);
CREATE INDEX ix_football_competitions_active ON football_competitions (is_active) WHERE is_active;

CREATE TABLE football_seasons (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id   bigint NOT NULL REFERENCES football_competitions(id) ON DELETE CASCADE,
    year             integer NOT NULL CHECK (year BETWEEN 1850 AND 2200),
    label            text NOT NULL,
    start_date       date,
    end_date         date,
    is_current       boolean NOT NULL DEFAULT false,
    UNIQUE (competition_id, year)
);

CREATE TABLE football_venues (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider     varchar(32) NOT NULL,
    external_id  text NOT NULL,
    name         text NOT NULL,
    city         text,
    capacity     integer CHECK (capacity IS NULL OR capacity >= 0),
    fetched_at   timestamptz NOT NULL,
    UNIQUE (provider, external_id)
);

CREATE TABLE football_teams (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider     varchar(32) NOT NULL,
    external_id  text NOT NULL,
    name         text NOT NULL,
    short_name   text,
    code         varchar(8),
    country_id   bigint REFERENCES football_countries(id),
    logo_url     text,
    founded      integer,
    venue_id     bigint REFERENCES football_venues(id),
    fetched_at   timestamptz NOT NULL,
    UNIQUE (provider, external_id)
);
CREATE INDEX ix_football_teams_name ON football_teams (lower(name));

CREATE TABLE football_players (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider      varchar(32) NOT NULL,
    external_id   text NOT NULL,
    name          text NOT NULL,
    birth_date    date,
    nationality   text,
    position      varchar(16),
    photo_url     text,
    fetched_at    timestamptz NOT NULL,
    UNIQUE (provider, external_id)
);

-- Maç durumu sağlayıcıdan bağımsız normalize edilir; ham kod status_detail'de saklanır.
CREATE TABLE football_fixtures (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider           varchar(32) NOT NULL,
    external_id        text NOT NULL,
    season_id          bigint NOT NULL REFERENCES football_seasons(id),
    round              text,
    kickoff_at         timestamptz NOT NULL,
    status             varchar(16) NOT NULL CHECK (status IN (
                           'tbd', 'scheduled', 'live', 'halftime', 'finished', 'postponed',
                           'suspended', 'cancelled', 'abandoned', 'awarded')),
    status_detail      varchar(32),
    minute             smallint CHECK (minute IS NULL OR minute BETWEEN 0 AND 200),
    home_team_id       bigint NOT NULL REFERENCES football_teams(id),
    away_team_id       bigint NOT NULL REFERENCES football_teams(id),
    venue_id           bigint REFERENCES football_venues(id),
    referee            text,
    -- Uzatmalar dahil, penaltı atışları hariç skor.
    home_goals         smallint CHECK (home_goals >= 0),
    away_goals         smallint CHECK (away_goals >= 0),
    ht_home            smallint CHECK (ht_home >= 0),
    ht_away            smallint CHECK (ht_away >= 0),
    -- Normal süre (90 dk) skoru; modeller bunu kullanır.
    ft_home            smallint CHECK (ft_home >= 0),
    ft_away            smallint CHECK (ft_away >= 0),
    -- Yalnızca uzatma devresinde atılan goller ve penaltı atışları.
    et_home            smallint CHECK (et_home >= 0),
    et_away            smallint CHECK (et_away >= 0),
    pen_home           smallint CHECK (pen_home >= 0),
    pen_away           smallint CHECK (pen_away >= 0),
    fetched_at         timestamptz NOT NULL,
    source_updated_at  timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (provider, external_id),
    CHECK (home_team_id <> away_team_id),
    CONSTRAINT finished_has_score CHECK (status <> 'finished' OR (home_goals IS NOT NULL AND away_goals IS NOT NULL))
);
CREATE INDEX ix_football_fixtures_kickoff ON football_fixtures (kickoff_at);
CREATE INDEX ix_football_fixtures_status ON football_fixtures (status, kickoff_at);
CREATE INDEX ix_football_fixtures_season ON football_fixtures (season_id, kickoff_at);
CREATE INDEX ix_football_fixtures_home ON football_fixtures (home_team_id, kickoff_at);
CREATE INDEX ix_football_fixtures_away ON football_fixtures (away_team_id, kickoff_at);
CREATE TRIGGER trg_football_fixtures_updated_at BEFORE UPDATE ON football_fixtures
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE football_fixture_team_stats (
    fixture_id        bigint NOT NULL REFERENCES football_fixtures(id) ON DELETE CASCADE,
    team_id           bigint NOT NULL REFERENCES football_teams(id),
    shots_total       smallint CHECK (shots_total >= 0),
    shots_on_target   smallint CHECK (shots_on_target >= 0),
    possession_pct    numeric(5, 2) CHECK (possession_pct BETWEEN 0 AND 100),
    corners           smallint CHECK (corners >= 0),
    fouls             smallint CHECK (fouls >= 0),
    yellow_cards      smallint CHECK (yellow_cards >= 0),
    red_cards         smallint CHECK (red_cards >= 0),
    offsides          smallint CHECK (offsides >= 0),
    passes_total      integer CHECK (passes_total >= 0),
    passes_accurate   integer CHECK (passes_accurate >= 0),
    goalkeeper_saves  smallint CHECK (goalkeeper_saves >= 0),
    xg                numeric(6, 3) CHECK (xg >= 0),
    provider          varchar(32) NOT NULL,
    fetched_at        timestamptz NOT NULL,
    PRIMARY KEY (fixture_id, team_id)
);

CREATE TABLE football_standings (
    season_id      bigint NOT NULL REFERENCES football_seasons(id) ON DELETE CASCADE,
    group_name     text NOT NULL DEFAULT '',
    team_id        bigint NOT NULL REFERENCES football_teams(id),
    rank           smallint NOT NULL CHECK (rank > 0),
    played         smallint NOT NULL CHECK (played >= 0),
    won            smallint NOT NULL CHECK (won >= 0),
    drawn          smallint NOT NULL CHECK (drawn >= 0),
    lost           smallint NOT NULL CHECK (lost >= 0),
    goals_for      smallint NOT NULL CHECK (goals_for >= 0),
    goals_against  smallint NOT NULL CHECK (goals_against >= 0),
    points         smallint NOT NULL,
    form           varchar(16),
    provider       varchar(32) NOT NULL,
    fetched_at     timestamptz NOT NULL,
    PRIMARY KEY (season_id, group_name, team_id),
    CHECK (won + drawn + lost = played)
);

CREATE TABLE football_lineups (
    fixture_id   bigint NOT NULL REFERENCES football_fixtures(id) ON DELETE CASCADE,
    team_id      bigint NOT NULL REFERENCES football_teams(id),
    formation    varchar(16),
    coach_name   text,
    provider     varchar(32) NOT NULL,
    fetched_at   timestamptz NOT NULL,
    PRIMARY KEY (fixture_id, team_id)
);

CREATE TABLE football_lineup_players (
    fixture_id    bigint NOT NULL,
    team_id       bigint NOT NULL,
    player_id     bigint NOT NULL REFERENCES football_players(id),
    is_starter    boolean NOT NULL,
    shirt_number  smallint,
    position      varchar(8),
    grid          varchar(8),
    PRIMARY KEY (fixture_id, player_id),
    FOREIGN KEY (fixture_id, team_id) REFERENCES football_lineups(fixture_id, team_id) ON DELETE CASCADE
);

-- Sakat / cezalı / şüpheli oyuncular (maç bazında).
CREATE TABLE football_absences (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fixture_id   bigint NOT NULL REFERENCES football_fixtures(id) ON DELETE CASCADE,
    team_id      bigint NOT NULL REFERENCES football_teams(id),
    player_id    bigint NOT NULL REFERENCES football_players(id),
    status       varchar(16) NOT NULL CHECK (status IN ('missing', 'questionable')),
    category     varchar(16) NOT NULL CHECK (category IN ('injury', 'suspension', 'other')),
    reason       text,
    provider     varchar(32) NOT NULL,
    fetched_at   timestamptz NOT NULL,
    UNIQUE (fixture_id, player_id)
);

-- Sağlayıcının son bildirdiği kota ve sağlık durumu.
CREATE TABLE football_provider_status (
    provider          varchar(32) PRIMARY KEY,
    daily_limit       integer,
    daily_remaining   integer,
    minute_limit      integer,
    minute_remaining  integer,
    observed_at       timestamptz,
    last_success_at   timestamptz,
    last_error_at     timestamptz,
    last_error        text
);

CREATE TABLE football_sync_runs (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider     varchar(32) NOT NULL,
    job          varchar(32) NOT NULL,
    params       jsonb NOT NULL DEFAULT '{}'::jsonb,
    trigger      varchar(16) NOT NULL CHECK (trigger IN ('schedule', 'admin', 'cli')),
    status       varchar(16) NOT NULL CHECK (status IN ('running', 'succeeded', 'failed', 'skipped')),
    started_at   timestamptz NOT NULL,
    finished_at  timestamptz,
    requests     integer NOT NULL DEFAULT 0,
    items        integer NOT NULL DEFAULT 0,
    message      text
);
CREATE INDEX ix_football_sync_runs_recent ON football_sync_runs (started_at DESC);
CREATE INDEX ix_football_sync_runs_job ON football_sync_runs (job, started_at DESC);
