-- Match Intelligence AI — Faz 4: kupon geçmişi (değiştirilemez).
--
--   * Kupon, ilk maç başlamadan önce kaydedilmek zorunda.
--   * Kupon ve seçimlerinin içeriği sonradan DEĞİŞTİRİLEMEZ ve SİLİNEMEZ. Yalnızca sonuç alanları
--     (durum, sonuçlanma zamanı / seçim sonucu) "beklemede"den bir kez son duruma geçebilir.
--   * Oran ve beklenen değer alanı yoktur: lisanslı oran verisi (M-G2) bağlanınca ayrı geçişle eklenecek.

CREATE TABLE coupons (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            uuid REFERENCES users(id),
    created_at         timestamptz NOT NULL,
    first_kickoff_at   timestamptz NOT NULL,
    profile            varchar(16) NOT NULL CHECK (profile IN ('low', 'balanced', 'high', 'manual')),
    params             jsonb NOT NULL DEFAULT '{}'::jsonb,
    legs_count         smallint NOT NULL CHECK (legs_count BETWEEN 1 AND 20),
    joint_probability  double precision NOT NULL CHECK (joint_probability BETWEEN 0 AND 1),
    evaluation         jsonb NOT NULL,
    status             varchar(8) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'won', 'lost', 'void')),
    settled_at         timestamptz,
    CONSTRAINT coupon_before_kickoff CHECK (created_at < first_kickoff_at),
    CONSTRAINT settled_consistent CHECK ((status = 'pending') = (settled_at IS NULL))
);
CREATE INDEX ix_coupons_user ON coupons (user_id, created_at DESC);
CREATE INDEX ix_coupons_pending ON coupons (first_kickoff_at) WHERE status = 'pending';

CREATE TABLE coupon_legs (
    coupon_id      bigint NOT NULL REFERENCES coupons(id),
    position       smallint NOT NULL,
    prediction_id  bigint NOT NULL REFERENCES ml_predictions(id),
    fixture_id     bigint NOT NULL REFERENCES football_fixtures(id),
    market         varchar(16) NOT NULL,
    pick           varchar(16) NOT NULL,
    label          text NOT NULL,
    probability    double precision NOT NULL CHECK (probability BETWEEN 0 AND 1),
    reliability    varchar(8) NOT NULL,
    kickoff_at     timestamptz NOT NULL,
    result         varchar(8) NOT NULL DEFAULT 'pending' CHECK (result IN ('pending', 'won', 'lost', 'void')),
    PRIMARY KEY (coupon_id, position)
);
CREATE INDEX ix_coupon_legs_fixture ON coupon_legs (fixture_id) WHERE result = 'pending';

CREATE FUNCTION coupons_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'coupons silinemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF OLD.status <> 'pending' THEN
        RAISE EXCEPTION 'Sonuçlanmış kupon değiştirilemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF (NEW.id, NEW.user_id, NEW.created_at, NEW.first_kickoff_at, NEW.profile, NEW.params,
        NEW.legs_count, NEW.joint_probability, NEW.evaluation)
       IS DISTINCT FROM
       (OLD.id, OLD.user_id, OLD.created_at, OLD.first_kickoff_at, OLD.profile, OLD.params,
        OLD.legs_count, OLD.joint_probability, OLD.evaluation) THEN
        RAISE EXCEPTION 'Kupon içeriği değiştirilemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_coupons_guard BEFORE UPDATE OR DELETE ON coupons
    FOR EACH ROW EXECUTE FUNCTION coupons_guard();
CREATE TRIGGER trg_coupons_no_truncate BEFORE TRUNCATE ON coupons
    FOR EACH STATEMENT EXECUTE FUNCTION reject_modification();

CREATE FUNCTION coupon_legs_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'coupon_legs silinemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF OLD.result <> 'pending' THEN
        RAISE EXCEPTION 'Sonuçlanmış seçim değiştirilemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF (NEW.coupon_id, NEW.position, NEW.prediction_id, NEW.fixture_id, NEW.market, NEW.pick,
        NEW.label, NEW.probability, NEW.reliability, NEW.kickoff_at)
       IS DISTINCT FROM
       (OLD.coupon_id, OLD.position, OLD.prediction_id, OLD.fixture_id, OLD.market, OLD.pick,
        OLD.label, OLD.probability, OLD.reliability, OLD.kickoff_at) THEN
        RAISE EXCEPTION 'Kupon seçimi değiştirilemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_coupon_legs_guard BEFORE UPDATE OR DELETE ON coupon_legs
    FOR EACH ROW EXECUTE FUNCTION coupon_legs_guard();
CREATE TRIGGER trg_coupon_legs_no_truncate BEFORE TRUNCATE ON coupon_legs
    FOR EACH STATEMENT EXECUTE FUNCTION reject_modification();
