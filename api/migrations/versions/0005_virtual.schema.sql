-- Match Intelligence AI — Faz 5: sanal portföy simülasyonu.
--
-- Sanal birim (SB) GERÇEK PARA DEĞİLDİR: çekilemez, transfer edilemez, satın alınamaz, hiçbir ödeme
-- aracına dönüşmez. Tutarlar kuruş hassasiyetinde tamsayı (minor) tutulur.
--
--   * Defter yalnızca eklemeyle büyür; her kayıt bir önceki bakiyeye tutarı ekleyerek yeni bakiyeyi
--     taşır (tetikleyici hesaplar, uygulama değil). Bakiye negatife düşemez.
--   * Hesaplar arası transfer yoktur; defter kaydı türleri sabittir.
--   * Bilet içeriği değiştirilemez; sonuç bir kez yazılır.

CREATE TABLE virtual_accounts (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                uuid NOT NULL UNIQUE REFERENCES users(id),
    created_at             timestamptz NOT NULL,
    starting_balance_minor bigint NOT NULL CHECK (starting_balance_minor > 0),
    balance_minor          bigint NOT NULL CHECK (balance_minor >= 0),
    settings               jsonb NOT NULL,
    pending_settings       jsonb,
    pending_effective_at   timestamptz,
    reset_count            integer NOT NULL DEFAULT 0 CHECK (reset_count >= 0),
    last_reset_at          timestamptz
);

CREATE TABLE virtual_ledger (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id     bigint NOT NULL REFERENCES virtual_accounts(id),
    created_at     timestamptz NOT NULL,
    kind           varchar(16) NOT NULL CHECK (kind IN ('opening', 'stake', 'payout', 'refund', 'reset')),
    amount_minor   bigint NOT NULL,
    balance_minor  bigint NOT NULL CHECK (balance_minor >= 0),
    ticket_id      bigint,
    note           text,
    CHECK ((kind = 'stake') = (amount_minor < 0) OR (kind = 'reset')),
    CHECK (kind NOT IN ('stake', 'payout', 'refund') OR ticket_id IS NOT NULL)
);
CREATE INDEX ix_virtual_ledger_account ON virtual_ledger (account_id, id);

-- Bakiye zinciri: yeni bakiye = hesabın mevcut bakiyesi + tutar. Hesap satırı kilitlenir ve güncellenir.
CREATE FUNCTION virtual_ledger_apply() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    current bigint;
BEGIN
    SELECT balance_minor INTO current FROM virtual_accounts WHERE id = NEW.account_id FOR UPDATE;
    IF NEW.kind = 'opening' THEN
        IF EXISTS (SELECT 1 FROM virtual_ledger WHERE account_id = NEW.account_id) THEN
            RAISE EXCEPTION 'Açılış kaydı yalnızca bir kez' USING ERRCODE = 'check_violation';
        END IF;
        NEW.balance_minor := NEW.amount_minor;
    ELSE
        NEW.balance_minor := current + NEW.amount_minor;
    END IF;
    IF NEW.balance_minor < 0 THEN
        RAISE EXCEPTION 'Sanal bakiye yetersiz' USING ERRCODE = 'check_violation';
    END IF;
    UPDATE virtual_accounts SET balance_minor = NEW.balance_minor WHERE id = NEW.account_id;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_virtual_ledger_apply BEFORE INSERT ON virtual_ledger
    FOR EACH ROW EXECUTE FUNCTION virtual_ledger_apply();
CREATE TRIGGER trg_virtual_ledger_immutable BEFORE UPDATE OR DELETE ON virtual_ledger
    FOR EACH ROW EXECUTE FUNCTION reject_modification();
CREATE TRIGGER trg_virtual_ledger_no_truncate BEFORE TRUNCATE ON virtual_ledger
    FOR EACH STATEMENT EXECUTE FUNCTION reject_modification();

-- Hesap bakiyesi yalnızca defter tetikleyicisi üzerinden değişebilir.
CREATE FUNCTION virtual_accounts_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Sanal hesap silinemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.balance_minor IS DISTINCT FROM OLD.balance_minor
       AND pg_trigger_depth() < 2 THEN
        RAISE EXCEPTION 'Bakiye yalnızca defter kaydıyla değişir' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.user_id IS DISTINCT FROM OLD.user_id OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Sanal hesap sahibi değiştirilemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_virtual_accounts_guard BEFORE UPDATE OR DELETE ON virtual_accounts
    FOR EACH ROW EXECUTE FUNCTION virtual_accounts_guard();

CREATE TABLE virtual_tickets (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      bigint NOT NULL REFERENCES virtual_accounts(id),
    coupon_id       bigint NOT NULL REFERENCES coupons(id),
    created_at      timestamptz NOT NULL,
    stake_minor     bigint NOT NULL CHECK (stake_minor > 0),
    odds            numeric(10, 3) NOT NULL CHECK (odds > 1),
    odds_source     varchar(16) NOT NULL CHECK (odds_source IN ('model_fair', 'user_entered')),
    model_probability double precision NOT NULL CHECK (model_probability > 0 AND model_probability <= 1),
    staking         jsonb NOT NULL,
    status          varchar(8) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'won', 'lost', 'void')),
    payout_minor    bigint CHECK (payout_minor >= 0),
    settled_at      timestamptz,
    UNIQUE (account_id, coupon_id),
    CONSTRAINT settled_consistent CHECK ((status = 'pending') = (settled_at IS NULL)),
    CONSTRAINT payout_when_settled CHECK ((status = 'pending') = (payout_minor IS NULL))
);
CREATE INDEX ix_virtual_tickets_account ON virtual_tickets (account_id, created_at DESC);
CREATE INDEX ix_virtual_tickets_pending ON virtual_tickets (coupon_id) WHERE status = 'pending';
ALTER TABLE virtual_ledger ADD CONSTRAINT fk_virtual_ledger_ticket FOREIGN KEY (ticket_id) REFERENCES virtual_tickets(id);

CREATE FUNCTION virtual_tickets_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Sanal bilet silinemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF OLD.status <> 'pending' THEN
        RAISE EXCEPTION 'Sonuçlanmış sanal bilet değiştirilemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF (NEW.account_id, NEW.coupon_id, NEW.created_at, NEW.stake_minor, NEW.odds, NEW.odds_source,
        NEW.model_probability, NEW.staking)
       IS DISTINCT FROM
       (OLD.account_id, OLD.coupon_id, OLD.created_at, OLD.stake_minor, OLD.odds, OLD.odds_source,
        OLD.model_probability, OLD.staking) THEN
        RAISE EXCEPTION 'Sanal bilet içeriği değiştirilemez' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_virtual_tickets_guard BEFORE UPDATE OR DELETE ON virtual_tickets
    FOR EACH ROW EXECUTE FUNCTION virtual_tickets_guard();
